  static CountrySpec get defaultSpec => allSpecs.first;

  static List<CountrySpec> getByPurpose(DocumentPurpose purpose) {
    if (purpose == DocumentPurpose.all) return allSpecs;
    return allSpecs.where((spec) => spec.purpose == purpose).toList();
  }

  static CountrySpec findById(String id) {
    return allSpecs.firstWhere(
      (spec) => spec.id == id,
      orElse: () => defaultSpec,
    );
  }
